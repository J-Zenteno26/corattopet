function historyPageTypeForSide(int $index, string $side): string
{
    $mediaSide = $index % 2 === 0 ? 'left' : 'right';

    return $side === $mediaSide ? 'media' : 'story';
}

function renderHistoryDesktopPaper(array $chapter, int $index, string $side): void
{
    $pageType = historyPageTypeForSide($index, $side);
    $number = $index + 1;
    $memoryId = 'capitulo-' . $number . '-recuerdo-desktop';
    $mediaItems = $chapter['media'] ?? [];
    $mediaClass = 'history-chapter__media';

    if (count($mediaItems) > 1) {
        $mediaClass .= ' history-chapter__media--duo';
    }
    ?>
    <section
        class="history-paper history-paper--<?= e($side) ?> history-paper--<?= e($pageType) ?>"
        data-desktop-chapter="<?= $index ?>"
        data-page-type="<?= e($pageType) ?>"
    >
        <?php if ($pageType === 'media'): ?>
            <div
                class="<?= e($mediaClass) ?>"
                role="group"
                aria-label="<?= e($chapter['media_label']) ?>"
            >
                <?php foreach ($mediaItems as $media): ?>
                    <figure class="history-illustration">
                        <img
                            src="<?= e(appUrl('public/assets/img/historia/' . $media['file'])) ?>"
                            alt="<?= e($media['alt']) ?>"
                            loading="<?= $index === 0 ? 'eager' : 'lazy' ?>"
                            decoding="async"
                        >
                    </figure>
                <?php endforeach; ?>
            </div>
        <?php else: ?>
            <div class="history-story">
                <header class="history-chapter__heading">
                    <p class="history-chapter__number">
                        Capítulo <?= str_pad((string) $number, 2, '0', STR_PAD_LEFT) ?>
                    </p>

                    <h2 tabindex="-1">
                        <?= e($chapter['title']) ?>
                    </h2>
                </header>

                <div class="history-chapter__content">
                    <blockquote>
                        <?= e($chapter['quote']) ?>
                    </blockquote>

                    <p>
                        <?= e($chapter['summary']) ?>
                    </p>

                    <button
                        class="history-memory-toggle"
                        type="button"
                        aria-expanded="false"
                        aria-controls="<?= e($memoryId) ?>"
                        data-memory-toggle
                    >
                        Leer este recuerdo
                    </button>

                    <div
                        class="history-memory"
                        id="<?= e($memoryId) ?>"
                        data-memory
                        hidden
                    >
                        <p>
                            <?= e($chapter['memory']) ?>
                        </p>
                    </div>
                </div>
            </div>
        <?php endif; ?>
    </section>
    <?php
}

